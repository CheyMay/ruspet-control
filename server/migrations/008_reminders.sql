CREATE TABLE task_reminders (
 id uuid PRIMARY KEY, task_id text NOT NULL REFERENCES tasks,
 recipient_id text NOT NULL REFERENCES users, created_by text NOT NULL REFERENCES users,
 days integer[] NOT NULL, times text[] NOT NULL, start_date date NOT NULL,
 weeks integer NOT NULL CHECK(weeks BETWEEN 1 AND 52), enabled boolean NOT NULL DEFAULT true,
 version integer NOT NULL DEFAULT 1, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX task_reminders_task ON task_reminders(task_id);
CREATE TABLE task_alerts (
 id uuid PRIMARY KEY, dedupe_key text NOT NULL UNIQUE, recipient_id text NOT NULL REFERENCES users,
 task_id text REFERENCES tasks, reminder_id uuid REFERENCES task_reminders,
 kind text NOT NULL CHECK(kind IN ('task','morning','noon')),
 body text NOT NULL, due_at timestamptz NOT NULL, expires_at timestamptz NOT NULL,
 acknowledged_at timestamptz, canceled_at timestamptz, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX task_alerts_pending ON task_alerts(recipient_id,due_at) WHERE acknowledged_at IS NULL AND canceled_at IS NULL;
CREATE TABLE task_alert_deliveries (
 alert_id uuid NOT NULL REFERENCES task_alerts, slot integer NOT NULL,
 state text NOT NULL CHECK(state IN ('sending','sent','failed','uncertain')),
 created_at timestamptz NOT NULL DEFAULT now(), message_id bigint,
 PRIMARY KEY(alert_id,slot)
);
