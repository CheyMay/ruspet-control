CREATE TABLE task_sync_queue (
 id uuid PRIMARY KEY, task_id text NOT NULL REFERENCES tasks, task_version integer NOT NULL,
 payload jsonb NOT NULL, state text NOT NULL DEFAULT 'pending' CHECK(state IN ('pending','sent','failed')),
 attempts integer NOT NULL DEFAULT 0, retry_at timestamptz, created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(task_id,task_version)
);
